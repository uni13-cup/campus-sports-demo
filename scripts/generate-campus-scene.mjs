import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

import {
  ACTIVITY_GEO_BOUNDS,
  CAMPUS_MAP_SOURCE_URL,
  CAMPUS_VIEW_BOUNDS
} from '../src/game/campus.js'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(repositoryRoot, 'src/game/data/campus-data.js')
const bbox = [
  CAMPUS_VIEW_BOUNDS.west,
  CAMPUS_VIEW_BOUNDS.south,
  CAMPUS_VIEW_BOUNDS.east,
  CAMPUS_VIEW_BOUNDS.north
].join(',')
const apiUrl = `https://api.openstreetmap.org/api/0.6/map?bbox=${bbox}`

const response = await fetch(apiUrl, {
  headers: {
    'User-Agent': 'CampusSportsDemoDataBuilder/1.0 (https://github.com/uni13-cup/campus-sports-demo)'
  }
})
if (!response.ok) throw new Error(`OpenStreetMap request failed: ${response.status}`)

const xml = await response.text()
const nodes = parseNodes(xml)
const ways = parseWays(xml)
const features = []
const buildingBounds = []

for (const way of ways) {
  const coordinates = way.refs.map((ref) => nodes.get(ref)).filter(Boolean)
  if (coordinates.length < 2) continue

  const kind = classifyWay(way.tags)
  if (!kind) continue

  const isClosed = coordinates.length >= 4 &&
    coordinates[0][0] === coordinates.at(-1)[0] &&
    coordinates[0][1] === coordinates.at(-1)[1]
  const geometryType = isClosed && kind !== 'road' ? 'Polygon' : 'LineString'
  const geometryCoordinates = geometryType === 'Polygon' ? [coordinates] : coordinates

  features.push({
    type: 'Feature',
    id: `osm-way-${way.id}`,
    properties: {
      osmId: way.id,
      kind,
      class: way.tags.highway ?? way.tags.building ?? way.tags.leisure ??
        way.tags.landuse ?? way.tags.natural ?? way.tags.amenity ?? '',
      name: way.tags.name ?? ''
    },
    geometry: {
      type: geometryType,
      coordinates: geometryCoordinates
    }
  })

  if (kind === 'building' && isClosed) {
    const bounds = getCoordinateBounds(coordinates)
    if (intersects(bounds, ACTIVITY_GEO_BOUNDS)) {
      buildingBounds.push({
        id: `osm-building-${way.id}`,
        osmId: way.id,
        ...bounds
      })
    }
  }
}

const scene = {
  type: 'FeatureCollection',
  features
}
const metadata = {
  source: CAMPUS_MAP_SOURCE_URL,
  apiUrl,
  licence: 'OpenStreetMap data © OpenStreetMap contributors, ODbL 1.0',
  extractedOn: '2026-10-14',
  featureCount: features.length,
  activityBuildingCount: buildingBounds.length
}
const moduleText = `// Generated by scripts/generate-campus-scene.mjs.\n` +
  `// OpenStreetMap data © OpenStreetMap contributors, ODbL 1.0.\n` +
  `export const CAMPUS_DATA_META = ${JSON.stringify(metadata, null, 2)}\n\n` +
  `export const CAMPUS_SCENE = ${JSON.stringify(scene)}\n\n` +
  `export const CAMPUS_BUILDING_BOUNDS = ${JSON.stringify(buildingBounds, null, 2)}\n`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, moduleText, 'utf8')
console.log(JSON.stringify(metadata, null, 2))

function parseNodes(source) {
  const result = new Map()
  for (const match of source.matchAll(/<node\s+([^>]*?)\/?>(?:<\/node>)?/g)) {
    const attrs = parseAttributes(match[1])
    if (attrs.id && attrs.lon && attrs.lat) {
      result.set(attrs.id, [Number(attrs.lon), Number(attrs.lat)])
    }
  }
  return result
}

function parseWays(source) {
  const result = []
  for (const match of source.matchAll(/<way\s+([^>]*)>([\s\S]*?)<\/way>/g)) {
    const attrs = parseAttributes(match[1])
    const body = match[2]
    const refs = [...body.matchAll(/<nd\s+ref="([^"]+)"\s*\/>/g)]
      .map((item) => item[1])
    const tags = {}
    for (const tagMatch of body.matchAll(/<tag\s+([^>]*?)\/>/g)) {
      const tag = parseAttributes(tagMatch[1])
      if (tag.k) tags[tag.k] = tag.v ?? ''
    }
    result.push({ id: attrs.id, refs, tags })
  }
  return result
}

function parseAttributes(source) {
  const attrs = {}
  for (const match of source.matchAll(/([\w:-]+)="([^"]*)"/g)) {
    attrs[match[1]] = decodeXml(match[2])
  }
  return attrs
}

function decodeXml(value) {
  return value
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&')
}

function classifyWay(tags) {
  if (tags.building) return 'building'
  if (tags.natural === 'water' || tags.water || tags.waterway) return 'water'
  if (tags.highway) return 'road'
  if (tags.leisure) return 'leisure'
  if (['grass', 'forest', 'meadow', 'recreation_ground'].includes(tags.landuse)) {
    return 'green'
  }
  if (tags.amenity === 'university') return 'campus'
  return null
}

function getCoordinateBounds(coordinates) {
  const longitudes = coordinates.map(([longitude]) => longitude)
  const latitudes = coordinates.map(([, latitude]) => latitude)
  return {
    west: Math.min(...longitudes),
    south: Math.min(...latitudes),
    east: Math.max(...longitudes),
    north: Math.max(...latitudes)
  }
}

function intersects(left, right) {
  return !(
    left.east < right.west ||
    left.west > right.east ||
    left.north < right.south ||
    left.south > right.north
  )
}

